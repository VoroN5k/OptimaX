//! Лабораторія стабільності: чи не помиляється залізо під навантаженням (розгін, андервольт, XMP).
//!
//! Ідея перевірки: ті самі обчислення з тими самими вхідними даними мають давати той самий
//! результат до останнього біта. GPU раз за разом рахує кілька фіксованих завдань, а результат
//! кожного повтору звіряється з першим ([`check::Checker`]). Розбіжність — це помилка обчислень,
//! яку гра показала б хіба що артефактом чи вильотом.
//!
//! Навантаження працює в окремому процесі ([`worker`]): нестабільне залізо може його вбити, але
//! вікно програми лишиться живим і покаже це як результат. Спільний лише протокол
//! ([`protocol`]); рішення приймають чисті функції ([`verdict`]).
//!
//! Модуль нічого не розганяє й не змінює в системі. Тест без помилок не доводить стабільність у
//! кожній грі: він лише не знайшов помилок за цей час і на цьому навантаженні.

pub mod check;
#[cfg(windows)]
#[allow(unsafe_code)]
pub mod gpu;
pub mod protocol;
pub mod verdict;
pub mod worker;
